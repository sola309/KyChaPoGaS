def api(method, path, body=None):
    r = urllib.request.Request(API + path, method=method,
        data=(json.dumps(body, ensure_ascii=False).encode() if body is not None else None),
        headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(r, timeout=30) as f:
        raw = f.read()
    return json.loads(raw) if raw else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry", action="store_true")
    a = ap.parse_args()
    pins = [c for c in api("GET", "/clips/?track_id=54") if c.get("asset_id")]
    pins.sort(key=lambda c: c["start_frame"])
    starts = [pins[i] for i in range(0, len(pins) - 1, 2)]
    assert len(starts) == 67, len(starts)
    ts = datetime.date.today().isoformat()
    changed = 0
    for n, pin in enumerate(starts, 1):
        attrs = json.loads(pin.get("attrs_json") or "{}")
        old = attrs.get("intent", "")
        new = I[n]
        if old == new:
            continue
        if a.dry:
            print(f"C{n:02d} {pin['id']} @{pin['start_frame']}: {old[:40]!r} → {new[:60]!r}")
            changed += 1
            continue
        if "intent_v1" not in attrs:
            attrs["intent_v1"] = old
        attrs["intent"] = new
        st = attrs.get("story") or {}
        st.update({"by": "claude", "ts": ts, "version": "v2"})
        attrs["story"] = st
        api("PATCH", f"/clips/{pin['id']}", {"attrs_json": json.dumps(attrs, ensure_ascii=False)})
        changed += 1
    print(f"{'(dry) ' if a.dry else ''}updated {changed}/67 cut intents")


if __name__ == "__main__":
    main()
